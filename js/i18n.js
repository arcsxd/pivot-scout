let lang = 'pt';
try {
  lang = localStorage.getItem('ps-lang') || 'pt';
} catch { /* sem storage */ }

export const getLang = () => lang;

export function t(key, vars) {
  let s = STRINGS[lang]?.[key] ?? STRINGS.pt[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}

export function applyI18n(root = document) {
  document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));
  root.querySelectorAll('[data-i18n-title]').forEach((el) => (el.title = t(el.dataset.i18nTitle)));
}

/** Liga um botão que alterna PT/EN e chama onChange depois. */
export function bindLangToggle(btn, onChange) {
  const label = () => (btn.textContent = lang === 'pt' ? 'EN' : 'PT');
  label();
  btn.addEventListener('click', () => {
    lang = lang === 'pt' ? 'en' : 'pt';
    try {
      localStorage.setItem('ps-lang', lang);
    } catch { /* ok */ }
    label();
    applyI18n();
    onChange?.();
  });
}
